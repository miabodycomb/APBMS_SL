class SimpleNN(nn.Module):
    def __init__(self, input_dim=8, hidden_dim=128):
        """
        Simple two-layer MLP for regression on tabular data (California Housing).
        input_dim = number of features (8 for California Housing)
        """
        super(SimpleNN, self).__init__()
        self.fc1 = nn.Linear(input_dim, hidden_dim)  # Input → hidden
        self.fc2 = nn.Linear(hidden_dim, 1)          # Hidden → output (single continuous value)

    def forward(self, x):
        x = torch.relu(self.fc1(x))   # Hidden layer with ReLU activation
        x = self.fc2(x)               # Output layer (no activation for regression)
        return x

