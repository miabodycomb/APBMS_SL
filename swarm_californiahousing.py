        round_times, train_times, agg_times = [], [], []

        # 5) Training & aggregation
        for round_idx in range(NUM_GLOBAL_ROUNDS):
            print(f"  Round {round_idx+1}/{NUM_GLOBAL_ROUNDS}")
            t_round0 = time.perf_counter()

            # ---- Local training + communication ----
            t_train0 = time.perf_counter()
            with concurrent.futures.ThreadPoolExecutor() as executor:
                # Each node trains locally and broadcasts; all nodes gather
                executor.map(train_and_communicate, nodes, [nodes] * len(nodes))
            train_dt = time.perf_counter() - t_train0
            train_times.append(train_dt)

            # ---- Aggregation phase (with safety) ----
            t_agg0 = time.perf_counter()

            # SAFETY: ensure all nodes have packets before aggregation
            if not any(n.global_parameters for n in nodes):
                print("    No packets this round — rebroadcasting from all nodes.")
                for src in nodes:
                    pkt = src.broadcast_parameters()
                    for dst in nodes:
                        dst.gather_parameters(pkt)
            else:
                # At least one node has packets; copy to any empty node
                donor = next((m for m in nodes if m.global_parameters), None)
                if donor:
                    for n in nodes:
                        if not n.global_parameters:
                            n.global_parameters = donor.global_parameters[:]  # shallow copy

            # Now it's safe to aggregate on every node
            for n in nodes:
                n.aggregate_parameters()

            agg_dt = time.perf_counter() - t_agg0
            agg_times.append(agg_dt)

            # ---- Round timing summary ----
            round_dt = time.perf_counter() - t_round0
            round_times.append(round_dt)
            print(f"    Round time={round_dt:.2f}s | train={train_dt:.2f}s | agg={agg_dt:.2f}s")

