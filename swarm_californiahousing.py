def model_parameters_to_string(model, limit=5):
    """
    Convert model parameters to a readable string (truncated for brevity).
    Works for regression and classification models alike.

    Parameters:
        model: nn.Module
        limit (int): number of parameter values to show per tensor
    """
    params_str = "Model Parameters:\n"
    for name, param in model.named_parameters():
        params_str += f"Name: {name}, Shape: {tuple(param.shape)}\n"
        # Show only a few values per tensor to avoid massive printouts
        flat = param.data.view(-1)
        shown = flat[:limit].tolist()
        params_str += f"Sample values: {shown}"
        if flat.numel() > limit:
            params_str += " ...\n"
        else:
            params_str += "\n"
        params_str += "-" * 50 + "\n"
    return params_str

## NODES PARAMS[0] == balance_score, weighting, rmse

class Node:
    def __init__(self, node_id, train_loader: DataLoader, test_loader: DataLoader, weighting, aggregation_methodology):
        """
        Node for Regression (California Housing)
        Mirrors the MNIST Node structure but uses regression logic.
        """
        self.__train_loader = train_loader
        self.test_loader = test_loader
        self.node_id = node_id
        self.global_parameters = []
        self.model = SimpleNN(input_dim=8)
        self.criterion = nn.MSELoss()
        self.optimizer = optim.Adam(self.model.parameters(), lr=LEARNING_RATE)

        self.weighting = weighting
        self.aggregation_methodology = aggregation_methodology
        self.balance_score = self.get_balance_score()
        self.current_rmse = None
        self.rmse_scores = []
        self.mae_scores = []
        self.r2_scores = []

    # ----------------------------------------------------
    def get_model(self):
        return self.model

    def get_balance_score(self):
        """
        Compute balance score based on evenness of target distribution.
        """
        all_targets = []
        for _, y in self.__train_loader:
            all_targets.extend(y.numpy().flatten())
        if len(all_targets) == 0:
            return 0.0
        hist, _ = np.histogram(all_targets, bins=10, density=True)
        hist = hist / np.sum(hist)
        score = 1 - np.std(hist)
        return float(score)

    # ----------------------------------------------------
    def broadcast_parameters(self):
        """
        Return packet of parameters: [balance_score, weighting, current_rmse, params...]
        """
        packet = [self.balance_score, self.weighting, self.current_rmse or 0.0]
        for p in self.model.parameters():
            packet.append(p.clone())
        return packet

    def gather_parameters(self, params):
        print(f"Gathered Parameters for Node {self.node_id}")
        self.global_parameters.append(params)
        print(f"Length of Gathered Parameters for Node {self.node_id}: {len(self.global_parameters)}")

    # ----------------------------------------------------
    def average_parameters(self):
        if not self.global_parameters:
            raise RuntimeError("No gathered parameters.")
        pkts = [p[:] for p in self.global_parameters]
        template = pkts[0][3:]
        averaged = [torch.zeros_like(p) for p in template]
        for pkt in pkts:
            for i, t in enumerate(pkt[3:]):
                averaged[i] += t
        n = len(pkts)
        averaged = [a / n for a in averaged]
        return averaged

    def size_average_parameters(self):
        if not self.global_parameters:
            raise RuntimeError("No gathered parameters.")
        pkts = [p[:] for p in self.global_parameters]
        weights = [p[1] for p in pkts]
        total_w = sum(weights)
        template = pkts[0][3:]
        averaged = [torch.zeros_like(p) for p in template]
        for pkt, w in zip(pkts, weights):
            for i, t in enumerate(pkt[3:]):
                averaged[i] += t * w
        if total_w > 0:
            averaged = [a / total_w for a in averaged]
        return averaged

    def balance_average_parameters(self):
        if not self.global_parameters:
            raise RuntimeError("No gathered parameters.")
        pkts = [p[:] for p in self.global_parameters]
        balances = [p[0] for p in pkts]
        total_b = sum(balances)
        template = pkts[0][3:]
        averaged = [torch.zeros_like(p) for p in template]
        for pkt, b in zip(pkts, balances):
            for i, t in enumerate(pkt[3:]):
                averaged[i] += t * b
        if total_b > 0:
            averaged = [a / total_b for a in averaged]
        return averaged

    # ----------------------------------------------------
    def aggregate_parameters(self):
        if self.aggregation_methodology == "average":
            averaged_params = self.average_parameters()
        elif self.aggregation_methodology == "size_average":
            averaged_params = self.size_average_parameters()
        elif self.aggregation_methodology == "balance_average":
            averaged_params = self.balance_average_parameters()
        else:
            raise ValueError(f"Invalid aggregation method: {self.aggregation_methodology}")
        self.set_parameters(averaged_params)
        self.global_parameters = []

    def set_parameters(self, parameters):
        new_state = dict(zip(self.model.state_dict().keys(), parameters))
        self.model.load_state_dict(new_state)
        print(f"Set parameters for Node {self.node_id}")

    # ----------------------------------------------------
    def train(self):
        """
        Local training for NUM_LOCAL_EPOCHS.
        """
        self.model.train()
        for epoch in range(NUM_LOCAL_EPOCHS):
            total_loss = 0.0
            for X, y in self.__train_loader:
                self.optimizer.zero_grad()
                preds = self.model(X)
                loss = self.criterion(preds, y)
                loss.backward()
                self.optimizer.step()
                total_loss += loss.item()
            print(f"Node {self.node_id} | Epoch {epoch+1}/{NUM_LOCAL_EPOCHS} | Loss: {total_loss/len(self.__train_loader):.4f}")

        # Update RMSE after local training
        rmse, _, _ = evaluate(self.model, self.test_loader)
        self.current_rmse = rmse

    def evaluate(self):
        """
        Evaluate model on this node's test loader and record RMSE, MAE, R2.
        """
        self.model.eval()
        preds, actuals = [], []
        with torch.no_grad():
            for X, y in self.test_loader:
                out = self.model(X)
                preds.extend(out.cpu().numpy().flatten())
                actuals.extend(y.cpu().numpy().flatten())
        preds = np.array(preds)
        actuals = np.array(actuals)
        mse = np.mean((preds - actuals) ** 2)
        mae = np.mean(np.abs(preds - actuals))
        rmse = np.sqrt(mse)
        r2 = 1 - np.sum((preds - actuals) ** 2) / np.sum((actuals - np.mean(actuals)) ** 2)
        self.rmse_scores.append(rmse)
        self.mae_scores.append(mae)
        self.r2_scores.append(r2)
        self.current_rmse = rmse
        print(f"Node {self.node_id} | RMSE: {rmse:.3f}, MAE: {mae:.3f}, R2: {r2:.3f}")
        return rmse, mae, r2

def train_and_communicate(node, all_nodes):
    """
    Local training for one node, then broadcast its parameters so that
    ALL nodes (including self) gather them for aggregation.
    Works for both baseline and dynamic runs.
    """
    # Local update (updates node.current_rmse internally)
    node.train()

    # Optional: explicit evaluation log (RMSE/MAE/R2)
    rmse, mae, r2 = node.evaluate()
    print(f"Node {node.get_node_id()} metrics — RMSE: {rmse:.4f}, MAE: {mae:.4f}, R2: {r2:.4f}")

    # Broadcast my params; everyone gathers (keeps aggregation safe)
    packet = node.broadcast_parameters()
    for peer in all_nodes:
        peer.gather_parameters(packet)

def evaluate(model, test_loader):
    """
    Evaluate a regression model on a given DataLoader.
    Returns: RMSE, MAE, R2
    """
    model.eval()  # Set model to evaluation mode
    all_targets = []
    all_predictions = []

    with torch.no_grad():
        for features, targets in test_loader:
            outputs = model(features)
            all_targets.extend(targets.cpu().numpy().flatten())
            all_predictions.extend(outputs.cpu().numpy().flatten())

    all_targets = np.array(all_targets)
    all_predictions = np.array(all_predictions)

    # Regression metrics
    mse = np.mean((all_predictions - all_targets) ** 2)
    mae = np.mean(np.abs(all_predictions - all_targets))
    rmse = np.sqrt(mse)
    r2 = 1 - np.sum((all_predictions - all_targets) ** 2) / np.sum((all_targets - np.mean(all_targets)) ** 2)

    return rmse, mae, r2

# Function to write regression metrics to a CSV file
def write_metrics_to_csv(filename, metrics_list):
    """
    metrics_list = [aggregation_method, RMSE, MAE, R2]
    """
    file_exists = os.path.isfile(filename)

    with open(filename, mode='a', newline='') as file:
        writer = csv.writer(file)

        # Write header only when the file is created
        if not file_exists:
            writer.writerow(['Aggregation Method', 'RMSE', 'MAE', 'R2'])

        # Write the data
        writer.writerow(metrics_list)

    print(f"Regression metrics written to {filename}")

