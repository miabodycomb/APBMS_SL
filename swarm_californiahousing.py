def load_data(normalize=True, seed=42):
    """
    Load and preprocess the California Housing dataset for regression.
    Mirrors the MNIST loader structure for consistency.
    """
    from sklearn.datasets import fetch_california_housing
    import numpy as np
    import torch

    # Load dataset
    data = fetch_california_housing()
    X = data.data.astype(np.float32)
    y = data.target.astype(np.float32).reshape(-1, 1)

    # Normalize features
    if normalize:
        X = (X - X.mean(axis=0)) / (X.std(axis=0) + 1e-8)

    # Split into train/test sets (80/20 split)
    n = X.shape[0]
    rng = np.random.RandomState(seed)
    idx = rng.permutation(n)
    n_train = int(0.8 * n)
    train_idx, test_idx = idx[:n_train], idx[n_train:]

    # Create torch tensors
    X_train = torch.tensor(X[train_idx])
    y_train = torch.tensor(y[train_idx])
    X_test = torch.tensor(X[test_idx])
    y_test = torch.tensor(y[test_idx])

    print("California Housing data has been loaded.")
    return (X_train, y_train), (X_test, y_test)

def split_data_nodes(dataset, num_nodes, alpha=0.5, bins=10, seed=42):
    """
    Non-IID partitioning for regression:
    - Assumes `dataset` is a TensorDataset where the 2nd tensor is the continuous target (shape [N,1] or [N]).
    - Discretizes targets into `bins` bins, then applies a Dirichlet(alpha) split per bin across clients.
    - Returns list of Subset(dataset, indices) per client + original dataset + size weightings.
    """
    import numpy as np
    import torch
    from torch.utils.data import Subset

    assert hasattr(dataset, "tensors") and len(dataset.tensors) >= 2, \
        "Expected a TensorDataset with features and targets in dataset.tensors"

    # Extract continuous targets and bin them to create label-like groups
    y = dataset.tensors[1].detach().cpu().numpy().reshape(-1)
    # rng = np.random.RandomState(seed)
    rng = np.random.default_rng()

    # Build bin ids over the continuous target
    edges = np.linspace(y.min(), y.max(), bins + 1)
    bin_ids = np.digitize(y, edges) - 1
    bin_ids = np.clip(bin_ids, 0, bins - 1)

    # Dirichlet split per bin
    client_indices = [[] for _ in range(num_nodes)]
    for c in range(bins):
        idx_c = np.where(bin_ids == c)[0]
        if idx_c.size == 0:
            continue
        rng.shuffle(idx_c)
        props = rng.dirichlet([alpha] * num_nodes)
        # turn proportions into index boundaries
        cuts = (np.cumsum(props) * len(idx_c)).astype(int)[:-1]
        parts = np.split(idx_c, cuts)
        for i, part in enumerate(parts):
            client_indices[i].extend(part.tolist())

    # Shuffle within each client split for good measure
    for lst in client_indices:
        rng.shuffle(lst)

    # Build Subset objects per client
    dataset_splits = [Subset(dataset, inds) for inds in client_indices]

    # Compute weightings for aggregators that use client size
    total = sum(len(s) for s in dataset_splits)
    weightings = [len(s) / total if total > 0 else 0.0 for s in dataset_splits]

    # Logging
    print(f"Data has been split into {num_nodes} clients (Dirichlet alpha={alpha}, bins={bins}, seed={seed})")
    for i, subset in enumerate(dataset_splits):
        print(f"  Size of client {i+1}: {len(subset)}")

    return dataset_splits, dataset, weightings

def create_data_loaders(subset, batch_size=BATCH_SIZE, num_workers=0):
    """
    Create train and validation DataLoaders for a regression subset.
    Mirrors MNIST structure but uses tabular regression data.
    """
    # Split subset into train/validation (80/20)
    val_size = int(0.2 * len(subset))
    train_size = len(subset) - val_size
    train_subset, val_subset = torch.utils.data.random_split(subset, [train_size, val_size])

    # Create DataLoaders
    train_loader = torch.utils.data.DataLoader(train_subset, batch_size=batch_size, shuffle=True, num_workers=num_workers)
    val_loader   = torch.utils.data.DataLoader(val_subset, batch_size=batch_size, shuffle=False, num_workers=num_workers)

    print(f"Data loaders created: {train_size} training samples, {val_size} validation samples.")
    return train_loader, val_loader

