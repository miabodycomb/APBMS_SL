def model_parameters_to_string(model, limit=3):
    """
    Convert model parameters to a readable string for inspection.
    Prints up to `limit` elements per parameter tensor for brevity.
    """
    params_str = "Model Parameters:\n"
    for name, param in model.named_parameters():
        params_str += f"Name: {name}, Shape: {tuple(param.shape)}\n"
        flat = param.data.flatten()
        shown = flat[:limit].tolist()
        params_str += f"Sample values: {shown}"
        if flat.numel() > limit:
            params_str += " ...\n"
        else:
            params_str += "\n"
        params_str += "-" * 50 + "\n"
    return params_str

class Node:
    def __init__(self, node_id, train_loader: DataLoader, test_loader: DataLoader, weighting, aggregation_methodology):
        """
        Node for Regression (California Housing).
        Mirrors original structure but replaces classification metrics with regression ones.
        """
        self.__train_loader = train_loader
        self.test_loader = test_loader
        self.node_id = node_id
        self.global_parameters = []

        # Model, loss, optimizer
        self.model = SimpleNN(input_dim=8)   # 8 features in California Housing
        self.criterion = nn.MSELoss()
        self.optimizer = optim.Adam(self.model.parameters(), lr=0.001)

        # Metrics & state
        self.weighting = weighting
        self.aggregation_methodology = aggregation_methodology
        self.balance_score = self.get_balance_score()
        self.current_epoch = 1

        # Regression metrics tracking
        self.rmse_scores = []
        self.mae_scores = []
        self.r2_scores = []
        self.current_rmse = None

    # -----------------------------
    # Core utilities
    # -----------------------------
    def update_epoch(self):
        self.current_epoch += 1

    def set_aggregation_methodology(self, methodology):
        self.aggregation_methodology = methodology

    def get_model(self):
        return self.model

    # -----------------------------
    # Balance & weighting
    # -----------------------------
    def get_balance_score(self):
        """
        Compute a balance score for regression based on how evenly
        distributed the target values are in this node's data.
        """
        all_targets = []
        for _, y in self.__train_loader:
            all_targets.extend(y.numpy().flatten())

        if len(all_targets) == 0:
            return 0.0

        hist, _ = np.histogram(all_targets, bins=10, density=True)
        hist = hist / np.sum(hist)
        score = 1 - np.std(hist)
        return float(score)

    # -----------------------------
    # Model broadcast & gather
    # -----------------------------
    def broadcast_parameters(self):
        """
        Broadcast packet: [balance_score, weighting, current_rmse, model params...]
        """
        params = [self.balance_score, self.weighting, self.current_rmse or 0.0]
        for p in self.model.parameters():
            params.append(p.clone())
        return params

    def gather_parameters(self, params):
        print(f"Gathered Parameters for Node {self.node_id}")
        self.global_parameters.append(params)
        print(f"Total gathered: {len(self.global_parameters)} packets")

    # -----------------------------
    # Aggregation (size / balance)
    # -----------------------------
    def size_average_parameters(self):
        if not self.global_parameters:
            raise RuntimeError("No gathered parameters to average.")

        params_copy = [pkt[:] for pkt in self.global_parameters]
        weightings = [p[1] for p in params_copy]

        template_tensors = params_copy[0][3:]
        averaged = [torch.zeros_like(t) for t in template_tensors]
        total_weight = sum(weightings)

        for pkt, w in zip(params_copy, weightings):
            for i, t in enumerate(pkt[3:]):
                averaged[i] += t * w

        if total_weight > 0:
            averaged = [t / total_weight for t in averaged]
        return averaged

    def balance_average_parameters(self):
        if not self.global_parameters:
            raise RuntimeError("No gathered parameters to average.")

        params_copy = [pkt[:] for pkt in self.global_parameters]
        balance_scores = [p[0] for p in params_copy]

        template_tensors = params_copy[0][3:]
        averaged = [torch.zeros_like(t) for t in template_tensors]
        total_balance = sum(balance_scores)

        for pkt, b in zip(params_copy, balance_scores):
            for i, t in enumerate(pkt[3:]):
                averaged[i] += t * b

        if total_balance > 0:
            averaged = [t / total_balance for t in averaged]
        return averaged

    # -----------------------------
    # Aggregation testing & selection
    # -----------------------------
    def test_aggregation(self):
        """
        Compare size vs balance aggregation by evaluating RMSE
        on this node's validation set. Return the better one (lower RMSE).
        """
        if not self.global_parameters:
            return self.aggregation_methodology or "balance_average"

        size_model = copy.deepcopy(self.model)
        bal_model = copy.deepcopy(self.model)

        size_params = self.size_average_parameters()
        bal_params = self.balance_average_parameters()

        size_model.load_state_dict(dict(zip(size_model.state_dict().keys(), size_params)))
        bal_model.load_state_dict(dict(zip(bal_model.state_dict().keys(), bal_params)))

        size_rmse, _, _ = evaluate(size_model, self.test_loader)
        bal_rmse, _, _ = evaluate(bal_model, self.test_loader)

        print(f"Node {self.node_id} | Size RMSE={size_rmse:.4f}, Balance RMSE={bal_rmse:.4f}")
        return "size" if size_rmse < bal_rmse else "balance"

    def aggregate_parameters(self):
        """
        Apply the currently chosen aggregation strategy to update this node's model.
        """
        if self.aggregation_methodology == "size_average":
            averaged_params = self.size_average_parameters()
        elif self.aggregation_methodology == "balance_average":
            averaged_params = self.balance_average_parameters()
        else:
            raise ValueError(f"Invalid aggregation methodology: {self.aggregation_methodology}")

        print(f"Node {self.node_id}: applying {self.aggregation_methodology}")
        self.set_parameters(averaged_params)
        self.global_parameters = []

    def set_parameters(self, parameters):
        new_state = dict(zip(self.model.state_dict().keys(), parameters))
        self.model.load_state_dict(new_state)
        print(f"Set parameters for node {self.node_id}")

    # -----------------------------
    # Training & evaluation
    # -----------------------------
    def train(self):
        self.model.train()
        for epoch in range(NUM_LOCAL_EPOCHS):
            total_loss = 0.0
            for X, y in self.__train_loader:
                self.optimizer.zero_grad()
                preds = self.model(X)
                loss = self.criterion(preds, y)
                loss.backward()
                self.optimizer.step()
                total_loss += loss.item()
            print(f"Node {self.node_id} | Epoch {epoch+1}/{NUM_LOCAL_EPOCHS} | Loss: {total_loss/len(self.__train_loader):.4f}")

    def evaluate(self):
        self.model.eval()
        preds, actuals = [], []

        with torch.no_grad():
            for X, y in self.test_loader:
                out = self.model(X)
                preds.extend(out.cpu().numpy().flatten())
                actuals.extend(y.cpu().numpy().flatten())

        preds = np.array(preds)
        actuals = np.array(actuals)
        mse = np.mean((preds - actuals) ** 2)
        mae = np.mean(np.abs(preds - actuals))
        rmse = np.sqrt(mse)
        r2 = 1 - np.sum((preds - actuals) ** 2) / np.sum((actuals - np.mean(actuals)) ** 2)

        self.rmse_scores.append(rmse)
        self.mae_scores.append(mae)
        self.r2_scores.append(r2)
        self.current_rmse = rmse

        print(f"Node {self.node_id} | RMSE: {rmse:.3f}, MAE: {mae:.3f}, R2: {r2:.3f}")
        return rmse, mae, r2

def train_and_communicate(node, nodes):
    # Train the node
    node.train()

    metrics = node.evaluate()
    print("Metrics for Node " + str(node.get_node_id()) + " : " + str(metrics))
    # Send parameters to all other nodes
    for other_node in nodes:
      print("NODE " + str(node.get_node_id()) + "  HAS BROADCASTED ")

      other_node.gather_parameters(node.broadcast_parameters())

def dynamic_aggregation(nodes):
    """
    Dynamically choose between size_average and balance_average
    based on which gives lower RMSE on each node's test set.
    """
    decisions = []
    for node in nodes:
        # Each node’s test_aggregation now returns which aggregation
        # gives LOWER RMSE rather than higher accuracy.
        decisions.append(node.test_aggregation())

    size_votes = decisions.count("size")
    balance_votes = decisions.count("balance")

    if size_votes > balance_votes:
        for node in nodes:
            node.set_aggregation_methodology("size_average")
        decision = "size"
    elif size_votes < balance_votes:
        for node in nodes:
            node.set_aggregation_methodology("balance_average")
        decision = "balance"
    else:
        for node in nodes:
            node.set_aggregation_methodology("balance_average")
        decision = "balance"

    print(f"Dynamic aggregation selected: {decision}")
    return decision

def evaluate(model, test_loader):
    """
    Evaluate regression model on test data.
    Returns: RMSE, MAE, R2
    """
    model.eval()  # evaluation mode

    all_targets = []
    all_predictions = []

    with torch.no_grad():
        for features, targets in test_loader:
            outputs = model(features)
            all_targets.extend(targets.cpu().numpy().flatten())
            all_predictions.extend(outputs.cpu().numpy().flatten())

    all_targets = np.array(all_targets)
    all_predictions = np.array(all_predictions)

    # Regression metrics
    mse = np.mean((all_predictions - all_targets) ** 2)
    mae = np.mean(np.abs(all_predictions - all_targets))
    rmse = np.sqrt(mse)
    r2 = 1 - np.sum((all_predictions - all_targets) ** 2) / np.sum((all_targets - np.mean(all_targets)) ** 2)

    return rmse, mae, r2

# Function to write regression metrics to a CSV file
def write_metrics_to_csv(filename, metrics_list):
    """
    metrics_list = [aggregation_method, RMSE, MAE, R2]
    """
    file_exists = os.path.isfile(filename)

    with open(filename, mode='a', newline='') as file:
        writer = csv.writer(file)

        # Write the header only if creating a new file
        if not file_exists:
            writer.writerow(['Aggregation Method', 'RMSE', 'MAE', 'R2'])

        # Append the metrics
        writer.writerow(metrics_list)

    print(f"Regression metrics written to {filename}")

