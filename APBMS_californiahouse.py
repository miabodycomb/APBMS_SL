class SimpleNN(nn.Module):
    def __init__(self, input_dim=8, hidden_dim=128):
        """
        Simple 2-layer fully connected network for regression.
        Default input_dim=8 (California Housing features).
        """
        super(SimpleNN, self).__init__()
        self.fc1 = nn.Linear(input_dim, hidden_dim)   # input -> hidden
        self.fc2 = nn.Linear(hidden_dim, 1)           # hidden -> single output value

    def forward(self, x):
        x = torch.relu(self.fc1(x))
        x = self.fc2(x)
        return x                                      # shape [batch, 1]

    def copy(self):
        # Create a new instance and copy parameters (keeps same interface)
        new_model = SimpleNN(input_dim=self.fc1.in_features,
                             hidden_dim=self.fc1.out_features)
        new_model.load_state_dict(self.state_dict())
        return new_model

